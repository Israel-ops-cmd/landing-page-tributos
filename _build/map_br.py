def inside(x, y, poly):
    c = False
    for i in range(len(poly)):
        x1, y1 = poly[i]; x2, y2 = poly[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c

def mapa_svg(step=0.82):
    x0, x1, y0, y1 = -75, -33.5, -34.5, 6
    s = 14  # px por grau
    W, H = (x1 - x0) * s, (y1 - y0) * s
    out = []
    y = y1
    row = 0
    while y > y0:
        x = x0 + (step / 2 if row % 2 else 0)
        while x < x1:
            if inside(x, y, BR):
                out.append('<circle class="dot" cx="%.1f" cy="%.1f" r="3.3"/>' % ((x - x0) * s, (y1 - y) * s))
            x += step
        y -= step * 0.87; row += 1
    for k, (px, py, home) in enumerate(PINS):
        cx, cy = (px - x0) * s, (y1 - py) * s
        d = '%.1fs' % (k * 0.37)
        out.append('<g class="pin%s"><circle class="pulse" cx="%.1f" cy="%.1f" r="%d" style="animation-delay:%s"/><circle class="core" cx="%.1f" cy="%.1f" r="%d"/></g>'
                   % (' home' if home else '', cx, cy, 9 if home else 6, d, cx, cy, 9 if home else 6))
    return '<svg viewBox="0 0 %d %d" role="img" aria-label="Mapa do Brasil">%s</svg>' % (W, H, ''.join(out))
